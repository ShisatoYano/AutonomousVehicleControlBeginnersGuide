"""
Unit test of noise generation in the Kalman filter and GNSS modules

Defect #164: the simulated noise was generated by multiplying np.random.randn()
by a variance instead of a standard deviation, so it did not match the
covariance the filters assume.

Author: qwist1233-cpu
"""

import sys
from math import sqrt
from pathlib import Path

import numpy as np
import pytest

SRC_DIR = str(Path(__file__).absolute().parent) + "/../src"
sys.path.append(SRC_DIR + "/simulations/localization/kalman_filter_1d")
sys.path.append(SRC_DIR + "/components/localization/kalman_filter")
sys.path.append(SRC_DIR + "/components/sensors/gnss")
sys.path.append(SRC_DIR + "/components/state")
sys.path.append(SRC_DIR + "/components/array")
import kalman_filter_1d_pos as kf_pos
import kalman_filter_1d_pos_spd as kf_pos_spd
import extended_kalman_filter_localizer as ekf_module
from extended_kalman_filter_localizer import ExtendedKalmanFilterLocalizer
from gnss import Gnss
from state import State

SAMPLES_NUM = 20000
TOLERANCE = 0.05 # 5[%] of the expected standard deviation


def test_gnss_noise_standard_deviation():
    """
    Noise added by GNSS has the standard deviation given to the constructor
    """

    np.random.seed(0)

    gnss = Gnss(x_noise_std=0.5, y_noise_std=0.5)
    state = State()
    for _ in range(SAMPLES_NUM): gnss.update(state)

    assert np.std(gnss.x_history) == pytest.approx(0.5, rel=TOLERANCE)
    assert np.std(gnss.y_history) == pytest.approx(0.5, rel=TOLERANCE)


def test_ekf_input_noise_standard_deviation(monkeypatch):
    """
    Noise added to the EKF's input is scaled by the standard deviation
    of acceleration and yaw rate, not by their variance
    """

    accel_noise, yaw_rate_noise_deg = 0.2, 10.0
    ekf = ExtendedKalmanFilterLocalizer(accel_noise=accel_noise,
                                       yaw_rate_noise=yaw_rate_noise_deg)

    # a deterministic randn makes the generated noise exactly 1 sigma
    monkeypatch.setattr(ekf_module.np.random, "randn", lambda *shape: np.ones(shape))

    accel_mps2, yaw_rate_rps, time_s = 1.0, 0.1, 0.1
    expected_input = np.array([[accel_mps2 + accel_noise],
                               [yaw_rate_rps + np.deg2rad(yaw_rate_noise_deg)]])
    expected_state = State.motion_model(np.zeros((4, 1)), expected_input, time_s)

    # observing the predicted position makes the innovation zero,
    # so the estimated state is the predicted state
    estimated_state = ekf.update(State(), accel_mps2, yaw_rate_rps, time_s,
                                 expected_state[0:2, :])

    assert estimated_state == pytest.approx(expected_state)


def test_1d_pos_observation_noise_standard_deviation():
    """
    Noise added to the observation of the 1D position filter has the
    standard deviation of the observation noise variance parameter
    """

    np.random.seed(0)

    kf = kf_pos.KalmanFilter1dPos(interval_sec=kf_pos.INTERVAL_SEC,
                                  input_velocity_ms=kf_pos.INPUT_VELOCITY_MS,
                                  input_noise_variance=kf_pos.INPUT_NOISE_VARIANCE,
                                  observation_noise_variance=kf_pos.OBSERVATION_NOISE_VARIANCE)
    observed = [kf.observation(x_prev=0.0) for _ in range(SAMPLES_NUM)]

    assert np.std(observed) == pytest.approx(sqrt(kf_pos.OBSERVATION_NOISE_VARIANCE),
                                             rel=TOLERANCE)


def test_1d_pos_spd_observation_noise_standard_deviation():
    """
    Noise added to the observation of the 1D position and speed filter has
    the standard deviation of the observation noise variance parameter
    """

    np.random.seed(0)

    obsrv_model = kf_pos_spd.ObservationModel(
        observation_noise_variance=kf_pos_spd.OBSERVATION_NOISE_VARIANCE)
    x_true = np.zeros((2, 1))
    observed = [obsrv_model.observe(x_true) for _ in range(SAMPLES_NUM)]

    assert np.std(observed) == pytest.approx(sqrt(kf_pos_spd.OBSERVATION_NOISE_VARIANCE),
                                             rel=TOLERANCE)


def test_1d_pos_spd_input_noise_is_zero_mean():
    """
    Noise added to the acceleration input has the standard deviation of the
    input noise variance parameter and does not shift the input on average
    """

    np.random.seed(0)

    input_accel_ms2 = np.array([[0.0]])
    noised = [kf_pos_spd.add_noise_input_accel(input_accel_ms2)[0, 0]
              for _ in range(SAMPLES_NUM)]

    assert np.std(noised) == pytest.approx(sqrt(kf_pos_spd.INPUT_NOISE_VARIANCE),
                                           rel=TOLERANCE)
    assert np.mean(noised) == pytest.approx(0.0, abs=0.05)
